-- A–Z strip (libraryscrubber.lua) and the wider footer page buttons (#37).
-- Rebuilt specs: the originals from GitHub PR #37 were lost with the account.
local Core = require("librarycore")

local function book(title, author, series)
    return { title = title, authors = author and { author } or nil, series = series }
end

describe("A–Z strip and page buttons", function()
    describe("pageHitPx", function()
        it("is about 10 mm and at least 120 px at 300 dpi", function()
            eq(Core.pageHitPx(300), 120)
            eq(Core.pageHitPx(400), math.floor(10 * 400 / 25.4 + 0.5))
        end)
        it("keeps 10 mm on lower densities", function()
            eq(Core.pageHitPx(167), math.floor(10 * 167 / 25.4 + 0.5))
        end)
        it("falls back to 167 dpi for nonsense", function()
            eq(Core.pageHitPx(nil), Core.pageHitPx(167))
            eq(Core.pageHitPx(0 / 0), Core.pageHitPx(167))
            eq(Core.pageHitPx(-5), Core.pageHitPx(167))
        end)
        it("reserves a narrow column, narrower than the page button", function()
            local col = Core.scrubberColumnWidth(300)
            eq(Core.scrubberWidth(300), col)
            eq(col < Core.pageHitPx(300), true)
            eq(col >= 44, true)
            local gutter = Core.scrubberGutterHit(300)
            eq(gutter < col, true, "the overlap is a gutter, not another column")
            eq(gutter >= 20, true)
        end)
    end)

    describe("gridContentWidth", function()
        it("gives the strip its width", function()
            eq(Core.gridContentWidth(1264, 120), 1144)
        end)
        it("never leaves the covers less than half the screen", function()
            eq(Core.gridContentWidth(200, 150), 100)
        end)
        it("is the full width with no strip", function()
            eq(Core.gridContentWidth(1264, 0), 1264)
            eq(Core.gridContentWidth(0, 0), 1)
        end)
    end)

    describe("showScrubber", function()
        it("is on unless turned off", function()
            eq(Core.showScrubber(nil), true)
            eq(Core.showScrubber({}), true)
            eq(Core.showScrubber({ show_scrubber = true }), true)
            eq(Core.showScrubber({ show_scrubber = false }), false)
        end)
    end)

    describe("scrubberBucket", function()
        it("files letters under their capital", function()
            eq(Core.scrubberBucket("dune"), "D")
            eq(Core.scrubberBucket("Zed"), "Z")
        end)
        it("folds accents", function()
            eq(Core.scrubberBucket("Émile"), "E")
            eq(Core.scrubberBucket("Ørsted"), "O")
            eq(Core.scrubberBucket("ñandú"), "N")
            eq(Core.scrubberBucket("Łódź"), "L")
        end)
        it("puts digits, symbols, blanks and other scripts under #", function()
            eq(Core.scrubberBucket("1984"), "#")
            eq(Core.scrubberBucket("¡Hola!"), "#")
            eq(Core.scrubberBucket(""), "#")
            eq(Core.scrubberBucket("   "), "#")
            eq(Core.scrubberBucket("Война и мир"), "#")
            eq(Core.scrubberBucket(nil), "#")
            eq(Core.scrubberBucket(Core.UNKNOWN), "#")
        end)
        it("skips leading spaces", function()
            eq(Core.scrubberBucket("  moby"), "M")
        end)
        it("has # then A to Z", function()
            eq(#Core.SCRUBBER_LETTERS, 27)
            eq(Core.SCRUBBER_LETTERS[1], "#")
            eq(Core.SCRUBBER_LETTERS[2], "A")
            eq(Core.SCRUBBER_LETTERS[27], "Z")
        end)
    end)

    describe("scrubberItemKey", function()
        local b = book("Dune", "Frank Herbert", "Dune Chronicles")
        it("reads the field for the sort", function()
            eq(Core.scrubberItemKey(b, "title"), "Dune")
            eq(Core.scrubberItemKey(b, "author"), "Frank Herbert")
            eq(Core.scrubberItemKey(b, "series"), "Dune Chronicles")
            eq(Core.scrubberItemKey({ name = "Fantasy" }, "name"), "Fantasy")
        end)
        it("uses the first of several authors, or a plain string", function()
            eq(Core.scrubberItemKey({ authors = { "A. One", "B. Two" } }, "author"), "A. One")
            eq(Core.scrubberItemKey({ authors = "Solo" }, "author"), "Solo")
        end)
        it("files a missing author or series as unknown", function()
            eq(Core.scrubberItemKey({ title = "x" }, "author"), Core.UNKNOWN)
            eq(Core.scrubberItemKey({ title = "x" }, "series"), Core.UNKNOWN)
        end)
        it("is empty for a non-table", function()
            eq(Core.scrubberItemKey(nil, "title"), "")
        end)
    end)

    describe("scrubberMode", function()
        it("shows for title, author and series sorts", function()
            eq(Core.scrubberMode{ kind = "books", sort = "title" }, "title")
            eq(Core.scrubberMode{ kind = "books", sort = "author" }, "author")
            eq(Core.scrubberMode{ kind = "books", sort = "series" }, "series")
        end)
        it("hides for date, last read and size", function()
            eq(Core.scrubberMode{ kind = "books", sort = "added" }, nil)
            eq(Core.scrubberMode{ kind = "books", sort = "recent" }, nil)
            eq(Core.scrubberMode{ kind = "books", sort = "size" }, nil)
        end)
        it("hides inside a series and when turned off", function()
            eq(Core.scrubberMode{ kind = "books", sort = "title", in_series = true }, nil)
            eq(Core.scrubberMode{ kind = "books", sort = "title", enabled = false }, nil)
        end)
        it("uses shelf names on the Authors, Series, Collections and Genres lists", function()
            for _, tab in ipairs({ "authors", "series", "collections", "genres" }) do
                eq(Core.scrubberMode{ kind = "groups", tab = tab, sort = "recent" }, "name", tab)
            end
            eq(Core.scrubberMode{ kind = "groups", tab = "books" }, nil)
        end)
        it("shows on an alphabetical cover grid and on single-column Compact", function()
            eq(Core.scrubberMode{ kind = "books", sort = "title", view = "grid" }, "title")
            eq(Core.scrubberMode{ kind = "books", sort = "author", view = "compact" }, "author")
            eq(Core.scrubberMode{ kind = "books", sort = "series", view = "list" }, "series")
            eq(Core.scrubberMode{ kind = "groups", tab = "authors", view = "list" }, "name")
            eq(Core.scrubberMode{ kind = "groups", tab = "authors", view = "compact" }, "name")
        end)
        it("stays off Compact · 2 columns", function()
            eq(Core.scrubberMode{ kind = "books", sort = "title", view = "compact2" }, nil)
            eq(Core.scrubberMode{ kind = "books", sort = "author", view = "compact2", pages = 6 }, nil)
            eq(Core.scrubberMode{ kind = "groups", tab = "authors", view = "compact2" }, nil)
            eq(Core.scrubberMode{ kind = "groups", tab = "series", view = "compact2", pages = 4 }, nil)
        end)
        it("shows the Series list only once it spans more than one page", function()
            eq(Core.scrubberMode{ kind = "groups", tab = "series", pages = 3 }, "name")
            eq(Core.scrubberMode{ kind = "groups", tab = "series", view = "grid", pages = 2 }, "name")
            eq(Core.scrubberMode{ kind = "groups", tab = "series", pages = 1 }, nil)
            -- page count not known yet: keep the strip until layout says otherwise
            eq(Core.scrubberMode{ kind = "groups", tab = "series" }, "name")
        end)
        it("hides a search that fits on one page and keeps a longer one", function()
            eq(Core.scrubberMode{ kind = "books", sort = "title", searching = true, pages = 1 }, nil)
            eq(Core.scrubberMode{ kind = "groups", tab = "authors", searching = true, pages = 1 }, nil)
            eq(Core.scrubberMode{ kind = "books", sort = "title", view = "compact", searching = true, pages = 1 }, nil)
            eq(Core.scrubberMode{ kind = "books", sort = "author", searching = true, pages = 2 }, "author")
            eq(Core.scrubberMode{ kind = "groups", tab = "series", searching = true, pages = 3 }, "name")
            eq(Core.scrubberMode{ kind = "groups", tab = "series", searching = true, pages = 1 }, nil)
        end)
        it("leaves a non-alphabetical sort unchanged and does not offer letters", function()
            local state = { kind = "books", sort = "recent", view = "compact", pages = 8 }
            eq(Core.scrubberMode(state), nil)
            eq(state.sort, "recent")
            state.sort = "added"
            eq(Core.scrubberMode(state), nil)
            eq(state.sort, "added")
            eq(Core.scrubberMode{ kind = "books", sort = "title", in_series = true, pages = 5 }, nil)
        end)
    end)

    describe("scrubberIndex", function()
        local items = {
            book("1984"), book("Anna Karenina"), book("Atonement"),
            book("Beloved"), book("Émile"), book("Emma"), book("Zorba"),
        }
        local idx = Core.scrubberIndex(items, 3)
        it("finds the first page for each letter", function()
            eq(idx.page["#"], 1)
            eq(idx.page.A, 1)
            eq(idx.page.B, 2)
            eq(idx.page.E, 2)
            eq(idx.page.Z, 3)
        end)
        it("marks empty letters inactive", function()
            eq(idx.active.C, false)
            eq(idx.page.C, nil)
            eq(idx.active.A, true)
        end)
        it("returns the target page or nil", function()
            eq(Core.scrubberTargetPage(idx, "E"), 2)
            eq(Core.scrubberTargetPage(idx, "Q"), nil)
            eq(Core.scrubberTargetPage(nil, "A"), nil)
        end)
        it("accepts a key function and a bad per_page", function()
            local by_author = Core.scrubberIndex({ book("x", "Zadie Smith"), book("y", "Al Gore") }, 0,
                function(it) return Core.scrubberItemKey(it, "author") end)
            eq(by_author.page.Z, 1)
            eq(by_author.page.A, 2)
        end)
        it("maps letters through a smaller page 1 and larger later pages", function()
            -- page 1: 1984, Anna; page 2: Atonement, Beloved, Émile; page 3: Emma, Zorba
            local idx = Core.scrubberIndex(items, 2, nil, 3)
            eq(idx.page["#"], 1)
            eq(idx.page.A, 1)
            eq(idx.page.B, 2)
            eq(idx.page.E, 2)
            eq(idx.page.Z, 3)
            eq(Core.scrubberTargetPage(idx, "Z"), 3)
        end)
    end)

    describe("scrubberIndex first positions", function()
        local items = {
            book("1984"), book("Anna Karenina"), book("Atonement"),
            book("Beloved"), book("Émile"), book("Emma"), book("Zorba"),
        }
        local idx = Core.scrubberIndex(items, 3)
        it("records the first item index for each letter", function()
            eq(idx.first["#"], 1)
            eq(idx.first.A, 2)
            eq(idx.first.B, 4)
            eq(idx.first.E, 5)
            eq(idx.first.Z, 7)
            eq(idx.first.C, nil)
        end)
        it("returns the first index or nil", function()
            eq(Core.scrubberFirstIndex(idx, "E"), 5)
            eq(Core.scrubberFirstIndex(idx, "Q"), nil)
            eq(Core.scrubberFirstIndex(nil, "A"), nil)
            eq(Core.scrubberFirstIndex(idx, nil), nil)
        end)
    end)

    describe("pageFrom", function()
        local items = { "a", "b", "c", "d", "e", "f", "g", "h", "i" }
        it("slices from an explicit start", function()
            same(Core.pageFrom(items, 4, 3), { "d", "e", "f" })
        end)
        it("returns fewer at the end of the list", function()
            same(Core.pageFrom(items, 8, 3), { "h", "i" })
        end)
        it("clamps a start past the end to the last item", function()
            same(Core.pageFrom(items, 99, 3), { "i" })
        end)
        it("is empty for an empty list", function()
            same(Core.pageFrom({}, 1, 3), {})
            same(Core.pageFrom(nil, 1, 3), {})
        end)
    end)

    describe("scrubberLetterAt", function()
        it("splits the strip evenly", function()
            eq(Core.scrubberLetterAt(100, 100, 270), "#")
            eq(Core.scrubberLetterAt(110, 100, 270), "A")
            eq(Core.scrubberLetterAt(369, 100, 270), "Z")
        end)
        it("is nil outside the strip", function()
            eq(Core.scrubberLetterAt(99, 100, 270), nil)
            eq(Core.scrubberLetterAt(370, 100, 270), nil)
            eq(Core.scrubberLetterAt(nil, 100, 270), nil)
        end)
    end)

    describe("scrubberBubbleRect", function()
        it("is about 22 mm, centred, at least 220 px at 300 dpi", function()
            local r = Core.scrubberBubbleRect(1264, 1680, 300)
            eq(r.w, 260)
            eq(r.h, 260)
            eq(r.x, math.floor((1264 - 260) / 2))
            eq(r.y, math.floor((1680 - 260) / 2))
        end)
        it("never takes most of a small screen", function()
            local r = Core.scrubberBubbleRect(300, 400, 300)
            eq(r.w, math.floor(300 * 0.42))
        end)
    end)

    describe("refresh", function()
        local strip = { x = 1144, y = 100, w = 120, h = 1400 }
        local bub = { x = 500, y = 700, w = 260, h = 260 }
        it("drags refresh only the strip and the bubble, fast", function()
            local r = Core.scrubberDragRefresh(strip, bub, nil)
            eq(r.mode, "fast")
            eq(#r.regions, 2)
        end)
        it("erases an old bubble that moved", function()
            local old = { x = 400, y = 700, w = 260, h = 260 }
            eq(#Core.scrubberRefreshRegions(strip, bub, old), 3)
            eq(#Core.scrubberRefreshRegions(strip, bub, bub), 2)
        end)
        it("repaints the body once when the page changed", function()
            local body = { x = 0, y = 100, w = 1264, h = 1400 }
            local r = Core.scrubberReleaseRefresh(true, body, strip, bub)
            eq(r.mode, "ui")
            same(r.regions, { body })
        end)
        it("clears just the strip and bubble when the page did not change", function()
            local r = Core.scrubberReleaseRefresh(false, nil, strip, bub)
            eq(r.mode, "ui")
            same(r.regions, { strip, bub })
        end)
    end)

    describe("plugin files", function()
        it("ships libraryscrubber.lua in the Makefile list", function()
            local f = assert(io.open("Makefile"))
            local mk = f:read("*a"); f:close()
            eq(mk:find("libraryscrubber.lua", 1, true) ~= nil, true)
        end)
        it("defaults the A–Z strip on in main.lua", function()
            local f = assert(io.open("library.koplugin/main.lua"))
            local src = f:read("*a"); f:close()
            eq(src:find("show_scrubber = true", 1, true) ~= nil, true)
        end)
    end)
end)
